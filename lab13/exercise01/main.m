% =========================================================
% ЛР13 — игра двух лиц с нулевой суммой
% =========================================================

clear;
clc;

%% =========================================================
% Платежная матрица
% =========================================================

A = [
    8 7 1;
    1 3 5;
    7 7 2
];

%% =========================================================
% Минимумы по строкам
% =========================================================

row_min = min(A,[],2);

%% Максимин
[alpha, maximin_strategy] = max(row_min);

%% =========================================================
% Максимумы по столбцам
% =========================================================

col_max = max(A,[],1);

%% Минимакс
[beta, minimax_strategy] = min(col_max);

%% =========================================================
% Проверка седловой точки
% =========================================================

if alpha == beta
    saddle = 'Есть';
else
    saddle = 'Нет';
end

%% =========================================================
% Вывод
% =========================================================

fprintf('Максиминная стратегия: A%d\n', maximin_strategy);
fprintf('Минимаксная стратегия: B%d\n', minimax_strategy);
fprintf('Нижняя цена игры: %.2f\n', alpha);
fprintf('Верхняя цена игры: %.2f\n', beta);
fprintf('Седловая точка: %s\n', saddle);

%% =========================================================
% График
% =========================================================

figure('Visible','off');

imagesc(A);
colorbar;

title('Платежная матрица игры');
xlabel('Стратегии игрока 2');
ylabel('Стратегии игрока 1');

exportgraphics(gcf,'lab13_game_matrix.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение результатов
% =========================================================

fileID = fopen('lab13_result.txt','w');

fprintf(fileID,'ЛР13 — игра двух лиц с нулевой суммой\n\n');

fprintf(fileID,'Максиминная стратегия: A%d\n', maximin_strategy);
fprintf(fileID,'Минимаксная стратегия: B%d\n', minimax_strategy);
fprintf(fileID,'Нижняя цена игры: %.2f\n', alpha);
fprintf(fileID,'Верхняя цена игры: %.2f\n', beta);
fprintf(fileID,'Седловая точка: %s\n', saddle);

fclose(fileID);

disp('Готово: lab13_result.txt и lab13_game_matrix.png');
