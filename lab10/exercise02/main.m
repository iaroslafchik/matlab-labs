% =========================================================
% ЛР10 — Задание 2 (исправленный linprog)
% =========================================================

clear;
clc;

%% Целевая функция (max -> min)

f = [-5; -4];

%% Ограничения A*x <= b

A = [
    1  -2;
   -1   1;
    1  -1
];

b = [
    6;
    8;
    10
];

%% Границы

lb = [0; 0];

%% =========================================================
% Решение
% =========================================================

opts = optimoptions('linprog','Display','none');

[x, fval, exitflag, output] = linprog(f, A, b, [], [], lb, [], opts);

%% =========================================================
% Проверка результата
% =========================================================

if exitflag <= 0
    disp('Решение не найдено или задача неограничена');
    disp(output.message);
    return;
end

%% =========================================================
% Восстановление max
% =========================================================

x1 = x(1);
x2 = x(2);
Fmax = -fval;

fprintf('x1 = %.6f\n', x1);
fprintf('x2 = %.6f\n', x2);
fprintf('Fmax = %.6f\n', Fmax);

%% =========================================================
% Сохранение
% =========================================================

fileID = fopen('lp_result_fixed.txt','w');

fprintf(fileID,'ЛР10 - Задание 2 (исправлено)\n\n');
fprintf(fileID,'x1 = %.6f\n', x1);
fprintf(fileID,'x2 = %.6f\n', x2);
fprintf(fileID,'Fmax = %.6f\n', Fmax);

fclose(fileID);

disp('Готово: lp_result_fixed.txt');
