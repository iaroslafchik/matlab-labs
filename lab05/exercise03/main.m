% =========================================================
% ЛР5 — Задание 3
% Цифровой/аналоговый фильтр по передаточной функции
% =========================================================

clear;
clc;
close all;

%% =========================================================
% Передаточная функция K(p)
% =========================================================

s = tf('s');

K = (0.2*s^2 + 0.01*s - 3) / (0.009*s^2 + 0.01*s);

%% =========================================================
% Входной сигнал
% x(t) = 2sin(2π·2t) + sin(2π·90t)
% =========================================================

Fs = 1000;
t = 0:1/Fs:2;

x = 2*sin(2*pi*2*t) + sin(2*pi*90*t);

%% =========================================================
% Выход системы (аналоговая модель)
% =========================================================

y = lsim(K, x, t);

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','Фильтр','NumberTitle','off');

subplot(2,1,1);
plot(t, x, 'LineWidth', 1.2);
grid on;
title('Сигнал до фильтрации');
xlabel('t');
ylabel('Амплитуда');

subplot(2,1,2);
plot(t, y, 'LineWidth', 1.2);
grid on;
title('Сигнал после фильтрации');
xlabel('t');
ylabel('Амплитуда');

%% =========================================================
% Сохранение
% =========================================================

exportgraphics(gcf, 'filter_result.png', 'Resolution', 300);
close(gcf);

fileID = fopen('filter_result.txt','w');

fprintf(fileID, 'ЛР5 - Задание 3\n\n');
fprintf(fileID, 'K(s) = (0.2*s^2 + 0.01*s - 3)/(0.009*s^2 + 0.01*s)\n\n');
fprintf(fileID, 'Сигнал:\n');
fprintf(fileID, 'x(t)=2sin(2π·2t)+sin(2π·90t)\n');

fclose(fileID);

disp('Готово: filter_result.png и filter_result.txt');

drawnow;
exit;
