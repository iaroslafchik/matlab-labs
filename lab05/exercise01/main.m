% =========================================================
% ЛР5 — Задание 1
% Z-преобразование (Symbolic Math Toolbox)
% =========================================================

clear;
clc;

%% Символьные переменные

syms n z

%% =========================================================
% 1) f(n) = 9
% =========================================================

f1 = 9;
X1 = ztrans(f1, n, z);

%% =========================================================
% 2) f(n) = 5n/3!
% =========================================================

f2 = 5*n/factorial(3);
X2 = ztrans(f2, n, z);

%% =========================================================
% 3) f(n) = 3^n
% =========================================================

f3 = 3^n;
X3 = ztrans(f3, n, z);

%% =========================================================
% Вывод
% =========================================================

disp('Z-преобразования:');

disp('1) f(n)=9');
pretty(X1)

disp('2) f(n)=5n/3!');
pretty(X2)

disp('3) f(n)=3^n');
pretty(X3)

%% =========================================================
% Сохранение в файл
% =========================================================

fileID = fopen('z_transform_symbolic.txt','w');

fprintf(fileID, 'ЛР5 - Задание 1\n\n');

fprintf(fileID, '1) f(n)=9\n');
fprintf(fileID, 'X(z)=\n%s\n\n', char(X1));

fprintf(fileID, '2) f(n)=5n/3!\n');
fprintf(fileID, 'X(z)=\n%s\n\n', char(X2));

fprintf(fileID, '3) f(n)=3^n\n');
fprintf(fileID, 'X(z)=\n%s\n', char(X3));

fclose(fileID);

disp('Готово: z_transform_symbolic.txt');
