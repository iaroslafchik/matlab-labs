% =========================================================
% ЛР5 — Задание 2
% Обратное Z-преобразование (Symbolic Math Toolbox)
% =========================================================

clear;
clc;

%% Символьные переменные

syms n z

%% =========================================================
% 1) F(z) = ((z+1)(z+2))/((z+5)(z+1))
% =========================================================

F1 = ((z+1)*(z+2))/((z+5)*(z+1));
f1 = iztrans(F1, z, n);

%% =========================================================
% 2) F(z) = (z-5)/(z+1)
% =========================================================

F2 = (z-5)/(z+1);
f2 = iztrans(F2, z, n);

%% =========================================================
% Вывод результатов
% =========================================================

disp('Обратное Z-преобразование:');

disp('1) F(z)=((z+1)(z+2))/((z+5)(z+1))');
pretty(simplify(f1))

disp('2) F(z)=(z-5)/(z+1)');
pretty(simplify(f2))

%% =========================================================
% Сохранение в файл
% =========================================================

fileID = fopen('inverse_z_transform_results.txt','w');

fprintf(fileID, 'ЛР5 - Задание 2\n\n');

fprintf(fileID, '1) F(z)=((z+1)(z+2))/((z+5)(z+1))\n');
fprintf(fileID, 'f(n)=\n%s\n\n', char(simplify(f1)));

fprintf(fileID, '2) F(z)=(z-5)/(z+1)\n');
fprintf(fileID, 'f(n)=\n%s\n', char(simplify(f2)));

fclose(fileID);

disp('Готово: inverse_z_transform_results.txt');
