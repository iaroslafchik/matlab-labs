% =========================================================
% ЛР3 — Задание 2
% RLC режекторный фильтр (Notch)
% =========================================================

clear;
clc;
close all;

%% Дано

f0 = 1700;      % Гц
df = 400;       % полоса

w0 = 2*pi*f0;

Q = f0 / df;

%% Выбор параметров L и C (произвольно, но согласованно)

C = 100e-9;                         % 100 нФ
L = 1 / ((2*pi*f0)^2 * C);          % из формулы резонанса

R = w0 * L / Q;                     % из добротности

fprintf('Параметры фильтра:\n');
fprintf('L = %.6f H\n', L);
fprintf('C = %.10f F\n', C);
fprintf('R = %.4f Ohm\n', R);

%% Частотная ось

f = linspace(1000, 2500, 5000);
w = 2*pi*f;

%% Передаточная функция (последовательный RLC, выход на R)

Z_R = R;
Z_L = 1j*w*L;
Z_C = 1./(1j*w*C);

H = Z_R ./ (Z_R + Z_L + Z_C);

H_mag = abs(H);

%% =========================================================
% АЧХ
% =========================================================

figure('Visible','off','Name','RLC Notch','NumberTitle','off');

plot(f, H_mag, 'LineWidth', 1.5);
grid on;

title('АЧХ RLC режекторного фильтра');
xlabel('Частота (Гц)');
ylabel('|H(f)|');

hold on;
xline(f0, '--r', 'f_0');

%% Сохранение

exportgraphics(gcf, 'rlc_notch.png', 'Resolution', 300);
close(gcf);

disp('Готово: rlc_notch.png');

drawnow;
exit;
