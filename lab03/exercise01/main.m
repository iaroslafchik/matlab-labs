% =========================================================
% ЛР3 — RLC фильтр (ФВЧ)
% Полностью исправленный вариант
% =========================================================

clear;
clc;
close all;

%% Параметры цепи

L = 0.050;      % Гн
C = 0.0001;     % Ф
R = 100;        % Ом

%% Частота среза

w0 = 1/sqrt(L*C);
f0 = w0/(2*pi);

fprintf('Частота среза f0 = %.4f Гц\n', f0);

%% Частотная ось для АЧХ

f = linspace(1, 5000, 5000);
w = 2*pi*f;

%% Передаточная функция ФВЧ

H = (1j*w*R) ./ (R + 1j*w*L + 1./(1j*w*C));
H_mag = abs(H);

%% =========================================================
% Входной сигнал
% =========================================================

Fs = 10000;
t = 0:1/Fs:0.1;

x_in = sin(2*pi*50*t) + 0.5*sin(2*pi*500*t);

%% FFT входа

X_in = fft(x_in);
N = length(X_in);

f_in = Fs*(0:N-1)/N;

%% =========================================================
% Фильтрация через АЧХ
% =========================================================

H_interp = interp1(f, H_mag, f_in, 'linear', 'extrap');

X_out = X_in .* H_interp;

x_out = real(ifft(X_out));

%% =========================================================
% Корректная индексация (без end/2)
% =========================================================

idx = 1:floor(N/2);

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','RLC ФВЧ','NumberTitle','off');

subplot(3,1,1);
plot(f, H_mag, 'LineWidth', 1.2);
grid on;
title('АЧХ RLC (ФВЧ)');
xlabel('Частота (Гц)');
ylabel('|H(f)|');

subplot(3,1,2);
plot(f_in(idx), abs(X_in(idx))/N, 'LineWidth', 1.2);
grid on;
title('Спектр входного сигнала');
xlabel('Частота (Гц)');
ylabel('Амплитуда');

subplot(3,1,3);
plot(f_in(idx), abs(X_out(idx))/N, 'LineWidth', 1.2);
grid on;
title('Спектр выходного сигнала');
xlabel('Частота (Гц)');
ylabel('Амплитуда');

%% Сохранение результата

exportgraphics(gcf, 'lab3_rlc_hpf.png', 'Resolution', 300);
close(gcf);

disp('Готово: lab3_rlc_hpf.png');

drawnow;
exit;
