% =========================================================
% ЛР4 — Задание 6
% Свёртка через Лаплас (реализация через conv)
% =========================================================

clear;
clc;
close all;

%% Временная ось

Fs = 1000;
t = 0:1/Fs:10;
dt = t(2) - t(1);

%% =========================================================
% Входной сигнал
% x(t) = 2 sin(2t) sin(t+1)
% =========================================================

x = 2*sin(2*t).*sin(t+1);

%% Импульсная характеристика

h = exp(-3*t);

%% =========================================================
% Свёртка (эквивалент Лапласу)
% =========================================================

y = conv(x, h) * dt;

ty = (0:length(y)-1)/Fs;

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','Свёртка Лаплас','NumberTitle','off');

subplot(3,1,1);
plot(t, x, 'LineWidth', 1.5);
grid on;
title('Входной сигнал x(t)');
xlabel('t');
ylabel('Амплитуда');

subplot(3,1,2);
plot(t, h, 'LineWidth', 1.5);
grid on;
title('Импульсная характеристика h(t)');
xlabel('t');
ylabel('Амплитуда');

subplot(3,1,3);
plot(ty, y, 'LineWidth', 1.5);
grid on;
title('Выходной сигнал y(t) = x*h');
xlabel('t');
ylabel('Амплитуда');

%% =========================================================
% Сохранение
% =========================================================

exportgraphics(gcf, 'lab4_task6.png', 'Resolution', 300);
close(gcf);

fileID = fopen('lab4_task6.txt','w');

fprintf(fileID, 'ЛР4 - Задание 6\n\n');
fprintf(fileID, 'x(t) = 2 sin(2t) sin(t+1)\n');
fprintf(fileID, 'h(t) = e^(-3t)\n\n');

fprintf(fileID, 't\t x(t)\t h(t)\n');

for i = 1:length(t)
    fprintf(fileID, '%.4f\t%.6f\t%.6f\n', t(i), x(i), h(i));
end

fclose(fileID);

disp('Готово: lab4_task6.png и lab4_task6.txt');

drawnow;
exit;
