% =========================================================
% ЛР4 — Задание 4
% Свёртка: y(t) = x(t) * h(t)
% =========================================================

clear;
clc;
close all;

%% Временная ось

Fs = 1000;
t = 0:1/Fs:5;
dt = t(2) - t(1);

%% =========================================================
% Входной сигнал: прямоугольный
% =========================================================

x = double(t >= 1 & t <= 3);

%% =========================================================
% Импульсная характеристика
% h(t) = -t * exp(-t^3)
% =========================================================

h = -t .* exp(-t.^3);

%% =========================================================
% Свёртка (численная)
% =========================================================

y = conv(x, h) * dt;

ty = (0:length(y)-1)/Fs;

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','Свёртка','NumberTitle','off');

subplot(3,1,1);
plot(t, x, 'LineWidth', 1.5);
grid on;
title('Входной сигнал x(t)');
xlabel('t');
ylabel('Амплитуда');

subplot(3,1,2);
plot(t, h, 'LineWidth', 1.5);
grid on;
title('Импульсная характеристика h(t)');
xlabel('t');
ylabel('Амплитуда');

subplot(3,1,3);
plot(ty, y, 'LineWidth', 1.5);
grid on;
title('Выходной сигнал y(t) = x(t) * h(t)');
xlabel('t');
ylabel('Амплитуда');

%% =========================================================
% Сохранение
% =========================================================

exportgraphics(gcf, 'lab4_convolution.png', 'Resolution', 300);
close(gcf);

%% Сохранение численных данных

fileID = fopen('lab4_convolution.txt','w');

fprintf(fileID, 'ЛР4 - Задание 4\n');
fprintf(fileID, 'x(t): прямоугольный сигнал\n');
fprintf(fileID, 'h(t) = -t * exp(-t^3)\n\n');

fprintf(fileID, 't\t x(t)\t h(t)\n');

for i = 1:length(t)
    fprintf(fileID, '%.4f\t%.4f\t%.6f\n', t(i), x(i), h(i));
end

fclose(fileID);

disp('Готово: lab4_convolution.png и lab4_convolution.txt');

drawnow;
exit;
