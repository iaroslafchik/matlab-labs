% =========================================================
% ЛР12 — задача принятия решений (Samsung vs Apple)
% =========================================================

clear;
clc;

%% =========================================================
% Матрица выигрышей
% =========================================================

A = [
    2  4  7;
   -1  3  5;
   -3  3 11
];

%% =========================================================
% Критерий Лапласа
% =========================================================

laplace = mean(A,2);

%% =========================================================
% Критерий Вальда
% =========================================================

wald = min(A,[],2);

%% =========================================================
% Критерий Севиджа
% =========================================================

best = max(A);
regret = best - A;
savage = max(regret,[],2);

%% =========================================================
% Критерий Гурвица
% =========================================================

alpha = 0.6;
hurwicz = alpha*max(A,[],2) + (1-alpha)*min(A,[],2);

%% =========================================================
% Оптимальные стратегии
% =========================================================

[~, lap] = max(laplace);
[~, wal] = max(wald);
[~, sav] = min(savage);
[~, hur] = max(hurwicz);

%% =========================================================
% Вывод в консоль
% =========================================================

fprintf('Лаплас: A%d\n', lap);
fprintf('Вальд: A%d\n', wal);
fprintf('Севидж: A%d\n', sav);
fprintf('Гурвиц: A%d\n', hur);

%% =========================================================
% Сохранение TXT
% =========================================================

fileID = fopen('lab12_samsung_result.txt','w');

fprintf(fileID,'ЛР12 — Samsung vs Apple\n\n');

fprintf(fileID,'Лаплас: A%d\n', lap);
fprintf(fileID,'Вальд: A%d\n', wal);
fprintf(fileID,'Севидж: A%d\n', sav);
fprintf(fileID,'Гурвиц: A%d\n', hur);

fprintf(fileID,'\nМатрица выигрышей:\n');
fprintf(fileID,'%d %d %d\n', A');

fclose(fileID);

%% =========================================================
% Сохранение CSV (таблица критериев)
% =========================================================

T = table(laplace, wald, savage, hurwicz, ...
    'RowNames', {'A1','A2','A3'});

writetable(T,'lab12_samsung_table.csv','WriteRowNames',true);

%% =========================================================
% Завершение
% =========================================================

disp('Готово: lab12_samsung_result.txt и lab12_samsung_table.csv');
