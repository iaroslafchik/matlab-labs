% =========================================================
% ЛР12 — молочная продукция (критерии + риски)
% =========================================================

clear;
clc;

%% =========================================================
% Матрица выигрышей
% =========================================================

A = [
   -2  1  1  1;
   -4  2  2  2;
   -6 -1  3  3
];

labels = {'A1 (100)','A2 (200)','A3 (300)'};

%% =========================================================
% Критерий Лапласа
% =========================================================

laplace = mean(A,2);

%% =========================================================
% Критерий Вальда
% =========================================================

wald = min(A,[],2);

%% =========================================================
% Критерий Севиджа (матрица рисков)
% =========================================================

best = max(A);
regret = best - A;
savage = max(regret,[],2);

%% =========================================================
% Критерий Гурвица
% =========================================================

alpha = 0.6;
hurwicz = alpha*max(A,[],2) + (1-alpha)*min(A,[],2);

%% =========================================================
% Выбор стратегий
% =========================================================

[~, lap] = max(laplace);
[~, wal] = max(wald);
[~, sav] = min(savage);
[~, hur] = max(hurwicz);

%% =========================================================
% Вывод
% =========================================================

fprintf('Лаплас: A%d\n', lap);
fprintf('Вальд: A%d\n', wal);
fprintf('Севидж: A%d\n', sav);
fprintf('Гурвиц: A%d\n', hur);

%% =========================================================
% График рисков (Севидж)
% =========================================================

figure('Visible','off');

bar(regret','grouped');
title('Матрица рисков (Севидж)');
xlabel('Состояния спроса');
ylabel('Потери (сожаления)');
legend(labels,'Location','northwest');
grid on;

exportgraphics(gcf,'lab12_milk_risk.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение результатов
% =========================================================

fileID = fopen('lab12_milk_result.txt','w');

fprintf(fileID,'ЛР12 — молочная продукция\n\n');

fprintf(fileID,'Лаплас: A%d\n', lap);
fprintf(fileID,'Вальд: A%d\n', wal);
fprintf(fileID,'Севидж: A%d\n', sav);
fprintf(fileID,'Гурвиц: A%d\n', hur);

fprintf(fileID,'\nМатрица выигрышей:\n');
fprintf(fileID,'%d %d %d %d\n', A');

fprintf(fileID,'\nМатрица рисков:\n');
fprintf(fileID,'%d %d %d %d\n', regret');

fclose(fileID);

disp('Готово: lab12_milk_result.txt и lab12_milk_risk.png');
