% =========================================================
% ЛР12 — критерии принятия решений
% =========================================================

clear;
clc;

A = [
    15 20 13 11;
    20 50 15 5;
    16 9 27 45;
    18 8 33 66
];

%% =========================================================
% Лаплас
% =========================================================

laplace = mean(A,2);

%% =========================================================
% Вальд
% =========================================================

wald = min(A,[],2);

%% =========================================================
% Севидж
% =========================================================

best = max(A);
regret = best - A;
savage = max(regret,[],2);

%% =========================================================
% Гурвиц
% =========================================================

alpha = 0.6;
hurwicz = alpha*max(A,[],2) + (1-alpha)*min(A,[],2);

%% =========================================================
% Выбор стратегий
% =========================================================

[~, lap] = max(laplace);
[~, wal] = max(wald);
[~, sav] = min(savage);
[~, hur] = max(hurwicz);

%% =========================================================
% Сохранение
% =========================================================

fileID = fopen('decision_result.txt','w');

fprintf(fileID,'ЛР12 — принятие решений\n\n');

fprintf(fileID,'Лаплас: A%d\n', lap);
fprintf(fileID,'Вальд: A%d\n', wal);
fprintf(fileID,'Севидж: A%d\n', sav);
fprintf(fileID,'Гурвиц: A%d\n', hur);

fclose(fileID);

disp('Готово: decision_result.txt');
