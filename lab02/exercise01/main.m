% =========================================================
% ЛР2 — Задание 1
% Интегральное преобразование Фурье (численно)
% =========================================================

clear;
clc;
close all;

%% Параметры

Fs = 2000;          % дискретизация
L  = 4096;
t = (0:L-1)/Fs;

dt = 1/Fs;

%% Параметры сигналов

N = 4;
a = 2;

Omega0 = 2*pi*50;
phi0 = pi/6;

H = double(t >= 0);

%% =========================================================
% 1) (1/(N-1)!)*t^(N-1)*e^(-a t)*H(t)
% =========================================================

x1 = (1/factorial(N-1)) .* (t.^(N-1)) .* exp(-a*t) .* H;

%% =========================================================
% 2) cos(Ω0 t + φ0) H(t)
% =========================================================

x2 = cos(Omega0*t + phi0) .* H;

%% =========================================================
% 3) cos(Ω0 t) H(t)
% =========================================================

x3 = cos(Omega0*t) .* H;

%% =========================================================
% Прямое преобразование Фурье (FFT как аппроксимация интеграла)
% =========================================================

X1 = fft(x1) * dt;
X2 = fft(x2) * dt;
X3 = fft(x3) * dt;

%% Частотная ось

f = Fs*(0:L/2-1)/L;
w = 2*pi*f;

%% Спектры

S1 = abs(X1);
S2 = abs(X2);
S3 = abs(X3);

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','Интегральное Фурье','NumberTitle','off');

% --- сигнал 1 ---
subplot(3,2,1);
plot(t, x1); grid on;
title('x1(t)');

subplot(3,2,2);
plot(w, S1(1:L/2)); grid on;
title('|X1(ω)|');

% --- сигнал 2 ---
subplot(3,2,3);
plot(t, x2); grid on;
title('x2(t)');

subplot(3,2,4);
plot(w, S2(1:L/2)); grid on;
title('|X2(ω)|');

% --- сигнал 3 ---
subplot(3,2,5);
plot(t, x3); grid on;
title('x3(t)');

subplot(3,2,6);
plot(w, S3(1:L/2)); grid on;
title('|X3(ω)|');

%% Сохранение

exportgraphics(gcf, 'lab2_task1_ft.png', 'Resolution', 300);
close(gcf);

disp('Готово: lab2_task1_ft.png');

drawnow;
exit;
