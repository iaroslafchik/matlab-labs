% =========================================================
% ЛР2 — Задание 2
% δ(t): сравнение ДПФ и интегрального Фурье
% =========================================================

clear;
clc;
close all;

%% Параметры

Fs = 2000;
L  = 4096;
t = (0:L-1)/Fs;
dt = 1/Fs;

%% δ(t) в дискретной форме

x = zeros(1, L);
x(1) = 1/dt;   % нормировка, чтобы сохранить свойство интеграла

%% =========================================================
% 1) Дискретное преобразование Фурье (DFT)
% =========================================================

X_dft = fft(x);

%% =========================================================
% 2) "Интегральное" преобразование (аппроксимация интеграла)
% =========================================================

X_int = fft(x) * dt;

%% Частотная ось

f = Fs*(0:L/2-1)/L;
w = 2*pi*f;

%% =========================================================
% Спектры
% =========================================================

S_dft = abs(X_dft);
S_int = abs(X_int);

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','Дельта-функция','NumberTitle','off');

subplot(3,1,1);
stem(t, x, 'filled');
grid on;
title('\delta(t) (дискретная аппроксимация)');
xlabel('t');
ylabel('Амплитуда');

subplot(3,1,2);
plot(w, S_dft(1:L/2));
grid on;
title('DFT спектр');
xlabel('\omega');
ylabel('|X(\omega)|');

subplot(3,1,3);
plot(w, S_int(1:L/2));
grid on;
title('Интегральный спектр (FFT·dt)');
xlabel('\omega');
ylabel('|X(\omega)|');

%% Сохранение

exportgraphics(gcf, 'lab2_task2_delta.png', 'Resolution', 300);
close(gcf);

disp('Готово: lab2_task2_delta.png');

drawnow;
exit;
