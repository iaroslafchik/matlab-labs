% =========================================================
% ЛР2 — Задание 3
% Обратное интегральное преобразование Фурье
% F(ω) = e^{-ω^2} · H(ω)
% =========================================================

clear;
clc;
close all;

%% Параметры

Wmax = 50;        % диапазон частот
Nw   = 4096;      % дискретизация по ω
dw   = (2*Wmax)/Nw;

omega = linspace(-Wmax, Wmax, Nw);

%% F(ω) = e^{-ω^2} H(ω)

H = double(omega >= 0);
F = exp(-omega.^2) .* H;

%% Временная ось

t = linspace(-5, 5, 300);

x = zeros(size(t));

%% =========================================================
% Численное обратное Фурье
% x(t) = (1/2π) ∫ F(ω)e^{jωt} dω
% =========================================================

for k = 1:length(t)
    x(k) = (1/(2*pi)) * sum(F .* exp(1j*omega*t(k))) * dw;
end

x = real(x);

%% =========================================================
% Прямое преобразование (для проверки)
% =========================================================

X_check = fft(x);

f = (0:Nw-1);

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','Обратное Фурье','NumberTitle','off');

% --- частотная область ---
subplot(2,1,1);
plot(omega, F, 'LineWidth', 1.2);
grid on;
title('F(\omega)');
xlabel('\omega');
ylabel('Амплитуда');

% --- временная область ---
subplot(2,1,2);
plot(t, x, 'LineWidth', 1.2);
grid on;
title('x(t) после обратного Фурье');
xlabel('t');
ylabel('Амплитуда');

%% Сохранение

exportgraphics(gcf, 'lab2_task3_ifft.png', 'Resolution', 300);
close(gcf);

disp('Готово: lab2_task3_ifft.png');

drawnow;
exit;
