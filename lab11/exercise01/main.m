% =========================================================
% ЛР11 — корректный график (без contourf)
% =========================================================

clear;
clc;

%% =========================================================
% Сетка
% =========================================================

[x1, x2] = meshgrid(0:0.05:10, 0:0.05:10);

%% =========================================================
% Ограничения
% =========================================================

c1 = (7*x1 - 4*x2 <= -28);
c2 = (-x1 + 3*x2 <= -15);
c3 = (x1 >= 0) & (x2 >= 0);

feasible = c1 & c2 & c3;

%% =========================================================
% Функция цели
% =========================================================

F = x1 + 3*x2;

%% =========================================================
% График области (через imagesc — стабильный метод)
% =========================================================

figure('Visible','off');

imagesc([0 10],[0 10],feasible);
set(gca,'YDir','normal');
colormap([1 1 1; 0.7 0.9 0.7]);
hold on;

%% =========================================================
% Линии уровня функции
% =========================================================

contour(x1, x2, F, 15, 'k');

title('ЛР11 — каноническая форма ЗЛП');
xlabel('x1');
ylabel('x2');
grid on;

%% =========================================================
% Сохранение графика
% =========================================================

exportgraphics(gcf,'lab11_graph.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение текста
% =========================================================

fileID = fopen('lab11_result.txt','w');

fprintf(fileID,'ЛР11 - каноническая форма\n\n');
fprintf(fileID,'f = x1 + 3x2\n');
fprintf(fileID,'7x1 - 4x2 <= -28\n');
fprintf(fileID,'-x1 + 3x2 <= -15\n');
fprintf(fileID,'x1 >= 0, x2 >= 0\n');

fclose(fileID);

disp('Готово: lab11_graph.png и lab11_result.txt');
