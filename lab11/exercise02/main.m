% =========================================================
% ЛР11 — целочисленная ЗЛП (графический метод)
% =========================================================

clear;
clc;

%% =========================================================
% Сетка целых точек
% =========================================================

[x1,x2] = meshgrid(0:1:10, 0:1:10);

%% =========================================================
% Ограничения
% =========================================================

c1 = (2*x1 + x2 <= 11);
c2 = (-3*x1 + 2*x2 <= 10);
c3 = (3*x1 + 4*x2 >= 20);

feasible = c1 & c2 & c3;

%% =========================================================
% Целевая функция
% =========================================================

F = 3*x1 - 2*x2;

F(~feasible) = NaN;

%% =========================================================
% Поиск максимума среди целых точек
% =========================================================

[maxF, idx] = max(F(:));

[x_opt, y_opt] = ind2sub(size(F), idx);

%% =========================================================
% График
% =========================================================

figure('Visible','off');

imagesc([0 10],[0 10],feasible);
set(gca,'YDir','normal');
colormap([1 1 1; 0.7 0.9 0.7]);
hold on;

contour(x1, x2, 3*x1 - 2*x2, 15, 'k');

plot(x_opt-1, y_opt-1, 'ro', 'MarkerSize', 10, 'LineWidth', 2);

title('Целочисленная ЗЛП');
xlabel('x1');
ylabel('x2');

%% =========================================================
% Сохранение графика
% =========================================================

exportgraphics(gcf,'integer_lp.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение результата
% =========================================================

fileID = fopen('integer_lp_result.txt','w');

fprintf(fileID,'ЛР11 - целочисленная ЗЛП\n\n');
fprintf(fileID,'x1 = %d\n', x_opt-1);
fprintf(fileID,'x2 = %d\n', y_opt-1);
fprintf(fileID,'Fmax = %.0f\n', maxF);

fclose(fileID);

disp('Готово: integer_lp.png и integer_lp_result.txt');
