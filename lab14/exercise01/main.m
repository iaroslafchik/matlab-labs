% =========================================================
% ЛР14 — формула Байеса
% =========================================================

clear;
clc;

%% =========================================================
% Исходные данные
% =========================================================

P_H = 0.08;

P_E_given_H = 0.40;

P_E_given_notH = 0.90;

%% =========================================================
% Дополнительная вероятность
% =========================================================

P_notH = 1 - P_H;

%% =========================================================
% Полная вероятность события E
% =========================================================

P_E = P_E_given_H * P_H + ...
      P_E_given_notH * P_notH;

%% =========================================================
% Формула Байеса
% =========================================================

P_H_given_E = (P_E_given_H * P_H) / P_E;

%% =========================================================
% Вывод
% =========================================================

fprintf('P(H|E) = %.6f\n', P_H_given_E);
fprintf('Вероятность = %.2f %%\n', ...
    P_H_given_E * 100);

%% =========================================================
% График
% =========================================================

figure('Visible','off');

bar([P_H, P_H_given_E]);

set(gca,'XTickLabel',{'P(H)','P(H|E)'});

title('Сравнение вероятностей');
ylabel('Вероятность');

grid on;

exportgraphics(gcf,'lab14_bayes.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение результатов
% =========================================================

fileID = fopen('lab14_bayes_result.txt','w');

fprintf(fileID,'ЛР14 — формула Байеса\n\n');

fprintf(fileID,'P(H)=%.4f\n',P_H);
fprintf(fileID,'P(E|H)=%.4f\n',P_E_given_H);
fprintf(fileID,'P(E|notH)=%.4f\n\n',P_E_given_notH);

fprintf(fileID,'P(H|E)=%.6f\n',P_H_given_E);
fprintf(fileID,'Вероятность = %.2f %%\n', ...
    P_H_given_E * 100);

fclose(fileID);

disp('Готово: lab14_bayes.png и lab14_bayes_result.txt');
