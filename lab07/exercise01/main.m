% =========================================================
% ЛР7 — Экстремумы функций
% =========================================================

clear;
clc;
close all;

%% =========================================================
% 1) f1
% =========================================================

f1 = @(x) 6*x.^2 + x;

x1 = -1/12;
y1 = f1(x1);

%% =========================================================
% 2) f2 (x >= 0)
% =========================================================

f2 = @(x) -5*sqrt(x) + 2*x - 1;

x2 = 25/16;
y2 = f2(x2);

x_f2 = linspace(0, 5, 500);

%% =========================================================
% 3) f3
% =========================================================

f3 = @(x) (2*x.^2 + x - 4) ./ (5*x.^2 + 6);

D = sqrt(349);
x3_1 = (17 + D)/10;
x3_2 = (17 - D)/10;

x_f3 = linspace(-5, 5, 1000);

%% =========================================================
% Графики
% =========================================================

figure('Visible','off','Name','ЛР7','NumberTitle','off');

subplot(3,1,1);
x = linspace(-2,2,500);
plot(x, f1(x),'LineWidth',1.2);
hold on;
plot(x1,y1,'ro');
grid on;
title('f1(x)=6x^2+x');

subplot(3,1,2);
plot(x_f2, f2(x_f2),'LineWidth',1.2);
hold on;
plot(x2,y2,'ro');
grid on;
title('f2(x)=-5√x+2x-1');

subplot(3,1,3);
plot(x_f3, f3(x_f3),'LineWidth',1.2);
hold on;
plot(x3_1, f3(x3_1),'ro');
plot(x3_2, f3(x3_2),'ro');
grid on;
title('f3(x)=(2x^2+x-4)/(5x^2+6)');

%% =========================================================
% Сохранение
% =========================================================

exportgraphics(gcf,'lab7_extrema.png','Resolution',300);
close(gcf);

fileID = fopen('lab7_extrema.txt','w');

fprintf(fileID,'ЛР7 - Экстремумы\n\n');

fprintf(fileID,'f1 min: x=%.6f, y=%.6f\n', x1, y1);
fprintf(fileID,'f2 min: x=%.6f, y=%.6f\n', x2, y2);
fprintf(fileID,'f3 crit1: x=%.6f\n', x3_1);
fprintf(fileID,'f3 crit2: x=%.6f\n', x3_2);

fclose(fileID);

disp('Готово: lab7_extrema.png и lab7_extrema.txt');
