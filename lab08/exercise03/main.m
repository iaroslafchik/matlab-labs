% =========================================================
% ЛР8 — Метод золотого сечения
% f(x)=x^2+6x-8
% =========================================================

clear;
clc;
close all;

%% Функция

f = @(x) x.^2 + 6*x - 8;

%% Интервал

a = -10;
b = 10;

eps = 0.001;

%% =========================================================
% Константа золотого сечения
% =========================================================

phi = (sqrt(5) - 1) / 2;

%% =========================================================
% Итерационный процесс
% =========================================================

x1 = b - phi*(b - a);
x2 = a + phi*(b - a);

f1 = f(x1);
f2 = f(x2);

while (b - a) > eps

    if f1 < f2
        b = x2;
        x2 = x1;
        f2 = f1;

        x1 = b - phi*(b - a);
        f1 = f(x1);
    else
        a = x1;
        x1 = x2;
        f1 = f2;

        x2 = a + phi*(b - a);
        f2 = f(x2);
    end

end

xmin = (a + b)/2;
ymin = f(xmin);

%% =========================================================
% График
% =========================================================

x = linspace(-10,10,500);

figure('Visible','off','Name','Золотое сечение','NumberTitle','off');

plot(x, f(x),'LineWidth',1.5);
grid on;
hold on;

plot(xmin, ymin, 'ro');

title('Метод золотого сечения');
xlabel('x');
ylabel('f(x)');

%% =========================================================
% Сохранение
% =========================================================

exportgraphics(gcf,'lab8_golden.png','Resolution',300);
close(gcf);

fileID = fopen('lab8_golden.txt','w');

fprintf(fileID,'ЛР8 - Метод золотого сечения\n\n');
fprintf(fileID,'xmin = %.6f\n', xmin);
fprintf(fileID,'f(xmin) = %.6f\n', ymin);
fprintf(fileID,'eps = %.4f\n', eps);

fclose(fileID);

disp('Готово: lab8_golden.png и lab8_golden.txt');
