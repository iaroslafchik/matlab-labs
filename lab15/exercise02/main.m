% =========================================================
% ЛР15 — метод анализа иерархий (Саати)
% =========================================================

clear;
clc;

%% =========================================================
% Названия альтернатив
% =========================================================

alts = {
    'Samsung S26'
    'Samsung S25'
    'iPhone 15'
    'iPhone 16'
};

%% =========================================================
% Матрица критериев Саати
% =========================================================

K = [
    1   2   3   5;
    1/2 1   2   4;
    1/3 1/2 1   3;
    1/5 1/4 1/3 1
];

%% =========================================================
% Нормировка
% =========================================================

K_norm = K ./ sum(K);

weights = mean(K_norm,2);

%% =========================================================
% Оценки альтернатив
% строки = смартфоны
% столбцы = критерии
% =========================================================

scores = [
    10 9 9 6;
     8 8 8 8;
     7 8 7 7;
     9 9 8 5
];

%% =========================================================
% Итоговые оценки
% =========================================================

final_scores = scores * weights;

%% =========================================================
% Лучшая альтернатива
% =========================================================

[max_score, idx] = max(final_scores);

%% =========================================================
% Вывод
% =========================================================

fprintf('Веса критериев:\n');
disp(weights);

fprintf('\nИтоговые оценки:\n');

for i = 1:length(alts)

    fprintf('%s : %.4f\n', ...
        alts{i}, final_scores(i));

end

fprintf('\nЛучшая альтернатива:\n');
fprintf('%s\n', alts{idx});

%% =========================================================
% График
% =========================================================

figure('Visible','off');

bar(final_scores);

set(gca,'XTickLabel',alts);

title('Метод Саати — итоговые оценки');
ylabel('Оценка');

grid on;

exportgraphics(gcf,'lab15_saaty.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение результатов
% =========================================================

fileID = fopen('lab15_saaty_result.txt','w');

fprintf(fileID,'ЛР15 — метод Саати\n\n');

fprintf(fileID,'Веса критериев:\n');

for i = 1:length(weights)

    fprintf(fileID,'%.4f\n',weights(i));

end

fprintf(fileID,'\nИтоговые оценки:\n');

for i = 1:length(alts)

    fprintf(fileID,'%s : %.4f\n', ...
        alts{i}, final_scores(i));

end

fprintf(fileID,'\nЛучшая альтернатива:\n');
fprintf(fileID,'%s\n', alts{idx});

fclose(fileID);

disp('Готово: lab15_saaty.png и lab15_saaty_result.txt');
