% =========================================================
% ЛР15 — продукционная экспертная система
% =========================================================

clear;
clc;

%% =========================================================
% Начальная база фактов
% =========================================================

facts = [4 6 7];

%% =========================================================
% Флаг изменений
% =========================================================

changed = true;

%% =========================================================
% Прямой вывод
% =========================================================

while changed

    changed = false;

    %% -----------------------------------------------------
    % P3: a4 -> a8
    %% -----------------------------------------------------

    if ismember(4,facts) && ~ismember(8,facts)

        facts(end+1) = 8;
        changed = true;

        fprintf('P3: alpha4 -> alpha8\n');

    end

    %% -----------------------------------------------------
    % P1: a6 & a7 & a8 -> a1
    %% -----------------------------------------------------

    if ismember(6,facts) && ...
       ismember(7,facts) && ...
       ismember(8,facts) && ...
       ~ismember(1,facts)

        facts(end+1) = 1;
        changed = true;

        fprintf('P1: alpha6 & alpha7 & alpha8 -> alpha1\n');

    end

    %% -----------------------------------------------------
    % P2: a3 & a5 -> a2
    %% -----------------------------------------------------

    if ismember(3,facts) && ...
       ismember(5,facts) && ...
       ~ismember(2,facts)

        facts(end+1) = 2;
        changed = true;

        fprintf('P2: alpha3 & alpha5 -> alpha2\n');

    end

    %% -----------------------------------------------------
    % P4: a8 & a5 -> a1
    %% -----------------------------------------------------

    if ismember(8,facts) && ...
       ismember(5,facts) && ...
       ~ismember(1,facts)

        facts(end+1) = 1;
        changed = true;

        fprintf('P4: alpha8 & alpha5 -> alpha1\n');

    end

end

%% =========================================================
% Сортировка
% =========================================================

facts = sort(unique(facts));

%% =========================================================
% Вывод результата
% =========================================================

fprintf('\nКонечная база фактов:\n');

for i = 1:length(facts)

    fprintf('alpha%d ', facts(i));

end

fprintf('\n');

%% =========================================================
% Граф вывода
% =========================================================

figure('Visible','off');

x = 1:length(facts);
y = ones(size(x));

plot(x,y,'ro','MarkerSize',12,'LineWidth',2);

text(x,y+0.05,string("a"+facts));

title('Конечная база знаний');

axis([0 length(facts)+1 0.8 1.3]);
grid on;

exportgraphics(gcf,'lab15_expert_system.png','Resolution',300);
close(gcf);

%% =========================================================
% Сохранение результата
% =========================================================

fileID = fopen('lab15_result.txt','w');

fprintf(fileID,'ЛР15 — экспертная система\n\n');

fprintf(fileID,'Конечная база фактов:\n');

for i = 1:length(facts)

    fprintf(fileID,'alpha%d ', facts(i));

end

fprintf(fileID,'\n');

fclose(fileID);

disp('Готово: lab15_result.txt и lab15_expert_system.png');
