% =========================================================
% ЛР9 — Метод Ньютона-Рафсона (экстремум)
% f(x)=x^2+3x+7
% =========================================================

clear;
clc;
close all;

%% Функция и производные

f  = @(x) x.^2 + 3*x + 7;
df = @(x) 2*x + 3;
d2f = @(x) 2;

%% =========================================================
% Начальное приближение
% =========================================================

x = 10;
eps = 0.001;

max_iter = 100;

iter = 0;

%% =========================================================
% Итерации Ньютона
% =========================================================

while abs(df(x)) > eps && iter < max_iter

    x = x - df(x)/d2f(x);

    iter = iter + 1;

end

xmin = x;
ymin = f(xmin);

%% =========================================================
% График
% =========================================================

x_plot = linspace(-10,10,500);

figure('Visible','off','Name','Ньютон-Рафсон','NumberTitle','off');

plot(x_plot, f(x_plot),'LineWidth',1.5);
grid on;
hold on;

plot(xmin, ymin, 'ro');

title('Метод Ньютона-Рафсона');
xlabel('x');
ylabel('f(x)');

%% =========================================================
% Сохранение
% =========================================================

exportgraphics(gcf,'lab9_newton.png','Resolution',300);
close(gcf);

fileID = fopen('lab9_newton.txt','w');

fprintf(fileID,'ЛР9 - Метод Ньютона-Рафсона\n\n');
fprintf(fileID,'xmin = %.6f\n', xmin);
fprintf(fileID,'f(xmin) = %.6f\n', ymin);
fprintf(fileID,'итераций = %d\n', iter);

fclose(fileID);

disp('Готово: lab9_newton.png и lab9_newton.txt');
