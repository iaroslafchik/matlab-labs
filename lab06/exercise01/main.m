% =========================================================
% ЛР6 — Условная энтропия (вариант 10)
% =========================================================

clear;
clc;

%% =========================================================
% Матрица p(x,y)
% =========================================================

P = [
    0   1/6 1/6;
    1/6 1/6 2/6;
    0   0   0
];

%% =========================================================
% Убираем нули
% =========================================================

Pnz = P(P > 0);

%% =========================================================
% Маргинальные распределения
% =========================================================

Px = sum(P,1);
Py = sum(P,2)';

%% =========================================================
% Энтропии
% =========================================================

H = @(p) -sum(p(p>0) .* log2(p(p>0)));

Hx  = H(Px);
Hy  = H(Py);
Hxy = H(Pnz);

Hx_y = Hxy - Hy;
Hy_x = Hxy - Hx;

%% =========================================================
% Вывод
% =========================================================

fprintf('H(X)   = %.4f\n', Hx);
fprintf('H(Y)   = %.4f\n', Hy);
fprintf('H(X,Y) = %.4f\n', Hxy);
fprintf('H(X|Y) = %.4f\n', Hx_y);
fprintf('H(Y|X) = %.4f\n', Hy_x);

%% =========================================================
% Сохранение
% =========================================================

fileID = fopen('entropy_results.txt','w');

fprintf(fileID, 'ЛР6 - Условная энтропия (вариант 10)\n\n');

fprintf(fileID, 'H(X) = %.6f\n', Hx);
fprintf(fileID, 'H(Y) = %.6f\n', Hy);
fprintf(fileID, 'H(X,Y) = %.6f\n', Hxy);
fprintf(fileID, 'H(X|Y) = %.6f\n', Hx_y);
fprintf(fileID, 'H(Y|X) = %.6f\n', Hy_x);

fclose(fileID);

disp('Готово: entropy_results.txt');
